#!/usr/bin/env python3
"""
gen_interface_spec.py — Generates per-domain INTERFACE-SPEC.md from the
code-derived interface catalog (corpus-wide).

Reads _index/interface-catalog/<domain-path>.yaml (NEVER the rulebase) and
writes <domain-path>/INTERFACE-SPEC.md.  Deterministic (byte-stable, no
timestamps).  --check mode like sibling tools.

Output ordering:
  Predicates, constructors, atoms, imports — catalog order (export-list order
  in the YAML; the catalog uses sort_keys=True on the YAML dump but list items
  retain source order).
  Profile contract keys — sorted alphabetically (the catalog carries them sorted).

Usage:
  python _tools/gen_interface_spec.py [--check]

  --check  Exit non-zero if any INTERFACE-SPEC.md would change (CI guard).
"""
import argparse
import sys
from pathlib import Path

import yaml

# ---------------------------------------------------------------------------
# Constants
# ---------------------------------------------------------------------------

GENERATED_BY = "_tools/gen_interface_spec.py"

# Header placed verbatim at the top of every generated INTERFACE-SPEC.md.
# {domain} is substituted per-file; all other text is literal.
_HEADER_TMPL = (
    "<!-- GENERATED by _tools/gen_interface_spec.py from"
    " _index/interface-catalog/{domain}.yaml —"
    " do not hand-edit; regenerate after any -module/profile change."
    " This file is the code-truth interface contract;"
    " narrative docs (SIGNATURE.md/NOTES.md) defer to it where they disagree. -->"
)

# Em-dash sentinel for absent/null doc strings.
_EM = "—"


# ---------------------------------------------------------------------------
# Low-level helpers
# ---------------------------------------------------------------------------

def _em(value):
    """Return *value* if truthy, else the em-dash sentinel."""
    return value if value else _EM


def _tick(name: str) -> str:
    """Wrap *name* in back-ticks."""
    return f"`{name}`"


def _escape_cell(value: str) -> str:
    """Escape pipe characters so they render literally inside Markdown table cells."""
    return str(value).replace("|", r"\|")


# ---------------------------------------------------------------------------
# Section renderers
# ---------------------------------------------------------------------------

def _render_predicates(rulebases: list, multi: bool) -> list:
    """Return lines for the Public Predicates section."""
    lines = ["## Public Predicates", ""]

    all_preds = [
        (rb.get("module"), p)
        for rb in rulebases
        for p in ((rb.get("exports") or {}).get("predicates") or [])
    ]

    if not all_preds:
        lines += ["*No public predicates exported.*", ""]
        return lines

    if multi:
        lines += [
            "| Predicate | Module | Args | Doc |",
            "|-----------|--------|------|-----|",
        ]
        for mod, p in all_preds:
            na = _tick(_escape_cell(f"{p['name']}/{p['arity']}"))
            args = ", ".join(_tick(_escape_cell(a)) for a in (p.get("args") or []))
            doc = _escape_cell(_em(p.get("doc")))
            lines.append(f"| {na} | {_tick(_escape_cell(mod or '?'))} | {args} | {doc} |")
    else:
        lines += [
            "| Predicate | Args | Doc |",
            "|-----------|------|-----|",
        ]
        for _, p in all_preds:
            na = _tick(_escape_cell(f"{p['name']}/{p['arity']}"))
            args = ", ".join(_tick(_escape_cell(a)) for a in (p.get("args") or []))
            doc = _escape_cell(_em(p.get("doc")))
            lines.append(f"| {na} | {args} | {doc} |")

    lines.append("")
    return lines


def _render_constructors(rulebases: list, multi: bool) -> list:
    """Return lines for the Result Constructors section."""
    lines = ["## Result Constructors", ""]

    all_ctors = [
        (rb.get("module"), c)
        for rb in rulebases
        for c in ((rb.get("exports") or {}).get("constructors") or [])
    ]

    if not all_ctors:
        lines += ["*No result constructors exported.*", ""]
        return lines

    if multi:
        lines += [
            "| Constructor | Module | Args | Doc |",
            "|-------------|--------|------|-----|",
        ]
        for mod, c in all_ctors:
            na = _tick(_escape_cell(f"{c['name']}/{c['arity']}"))
            args = ", ".join(_tick(_escape_cell(a)) for a in (c.get("args") or []))
            doc = _escape_cell(_em(c.get("doc")))
            lines.append(f"| {na} | {_tick(_escape_cell(mod or '?'))} | {args} | {doc} |")
    else:
        lines += [
            "| Constructor | Args | Doc |",
            "|-------------|------|-----|",
        ]
        for _, c in all_ctors:
            na = _tick(_escape_cell(f"{c['name']}/{c['arity']}"))
            args = ", ".join(_tick(_escape_cell(a)) for a in (c.get("args") or []))
            doc = _escape_cell(_em(c.get("doc")))
            lines.append(f"| {na} | {args} | {doc} |")

    lines.append("")
    return lines


def _render_atoms(rulebases: list) -> list:
    """Return lines for the Exported Atoms section (grouped by kind)."""
    lines = ["## Exported Atoms", ""]

    all_atoms = [
        a
        for rb in rulebases
        for a in ((rb.get("exports") or {}).get("atoms") or [])
    ]

    enums = [a["name"] for a in all_atoms if a.get("kind") == "enum"]
    citations = [a["name"] for a in all_atoms if a.get("kind") == "citation"]
    pkeys = [a["name"] for a in all_atoms if a.get("kind") == "profile_key"]

    if not (enums or citations or pkeys):
        lines += ["*No exported atoms.*", ""]
        return lines

    if enums:
        lines += [
            "### Enumerations",
            "",
            ", ".join(_tick(e) for e in enums),
            "",
        ]
    if citations:
        lines += [
            "### Citations",
            "",
            ", ".join(_tick(c) for c in citations),
            "",
        ]
    if pkeys:
        lines += [
            "### Profile Keys",
            "",
            ", ".join(_tick(k) for k in pkeys),
            "",
        ]

    return lines


def _render_imports(rulebases: list) -> list:
    """Return lines for the Imports section."""
    lines = ["## Imports", ""]

    all_imports = [
        imp_entry
        for rb in rulebases
        for imp_entry in (rb.get("imports") or [])
    ]

    if not all_imports:
        lines += ["*No imports.*", ""]
        return lines

    lines += [
        "| Module | Imported Names |",
        "|--------|----------------|",
    ]
    for imp_entry in all_imports:
        mod = imp_entry.get("module") or "—"
        names = imp_entry.get("names") or []
        if names:
            names_str = ", ".join(_tick(_escape_cell(n)) for n in names)
        else:
            names_str = "*(full module)*"
        lines.append(f"| {_tick(_escape_cell(mod))} | {names_str} |")

    lines.append("")
    return lines


def _render_profile(rulebases: list) -> list:
    """Return lines for the Profile Contract section."""
    lines = ["## Profile Contract", ""]

    all_keys: dict = {}
    any_non_null = False

    for rb in rulebases:
        prof = rb.get("profile")
        if prof is not None:
            any_non_null = True
            for key, info in (prof.get("keys") or {}).items():
                all_keys[key] = info

    if not any_non_null:
        lines += ["*No generated profile accessors (old-gen).*", ""]
        return lines

    if not all_keys:
        lines += ["*No profile keys declared.*", ""]
        return lines

    lines += [
        "| Key | Required | Default |",
        "|-----|----------|---------|",
    ]
    for key in sorted(all_keys.keys()):
        info = all_keys[key]
        req = "yes" if info.get("required", True) else "no"
        default = _tick(_escape_cell(str(info["default"]))) if info.get("default") is not None else _EM
        lines.append(f"| {_tick(_escape_cell(key))} | {req} | {default} |")

    lines.append("")
    return lines


def _render_observations(rulebases: list) -> list:
    """Return lines for the Observations section."""
    lines = ["## Observations", ""]

    date_reps: list = []
    seen_dr: set = set()
    all_warnings: list = []

    for rb in rulebases:
        obs = rb.get("observations") or {}
        for dr in (obs.get("date_rep") or []):
            if dr not in seen_dr:
                seen_dr.add(dr)
                date_reps.append(dr)
        warns = rb.get("warnings") or []
        if isinstance(warns, list):
            all_warnings.extend(warns)

    dr_str = (
        ", ".join(_tick(d) for d in date_reps)
        if date_reps
        else _EM
    )
    lines += [f"**Date representation:** {dr_str}", ""]

    if all_warnings:
        lines += ["**Parse warnings:**", ""]
        for w in all_warnings:
            lines.append(f"- {w}")
        lines.append("")
    else:
        lines += ["**Parse warnings:** none", ""]

    return lines


# ---------------------------------------------------------------------------
# Top-level renderer
# ---------------------------------------------------------------------------

def render_spec(catalog: dict) -> str:
    """
    Render an INTERFACE-SPEC.md string from a per-domain catalog dict.

    The output is deterministic and byte-stable (no timestamps, no randomness).
    All sections are rendered unconditionally; empty sections use sentinel text.
    """
    domain = catalog["domain"]
    rulebases = catalog.get("rulebases") or []
    manifest = catalog.get("manifest") or {}
    shape_family = manifest.get("shape_family") or _EM
    multi = catalog.get("multi_rulebase", False)

    lines: list = []

    # ── Header comment ──────────────────────────────────────────────────────
    lines.append(_HEADER_TMPL.format(domain=domain))
    lines.append("")

    # ── Title ────────────────────────────────────────────────────────────────
    lines.append(f"# Interface Contract: `{domain}`")
    lines.append("")

    # ── Module(s) + shape family ─────────────────────────────────────────────
    modules = [rb.get("module") for rb in rulebases if rb.get("module")]
    if multi:
        mod_str = ", ".join(_tick(m) for m in modules)
        lines.append(f"**Shape family:** `{shape_family}`  ")
        lines.append(f"**Modules:** {mod_str} *(multi-rulebase: {len(rulebases)} files)*")
    else:
        mod_str = _tick(modules[0]) if modules else _EM
        lines.append(f"**Shape family:** `{shape_family}`  ")
        lines.append(f"**Module:** {mod_str}")
    lines.append("")

    # ── Sections ─────────────────────────────────────────────────────────────
    lines.extend(_render_predicates(rulebases, multi))
    lines.extend(_render_constructors(rulebases, multi))
    lines.extend(_render_atoms(rulebases))
    lines.extend(_render_imports(rulebases))
    lines.extend(_render_profile(rulebases))
    lines.extend(_render_observations(rulebases))

    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Corpus run + check
# ---------------------------------------------------------------------------

def run(root, check: bool = False) -> int:
    """
    Discover all per-domain catalog YAMLs, render INTERFACE-SPEC.md for each.

    In --check mode: compare would-be output against existing files; return 1
    if any file would change or is missing, 0 otherwise.
    """
    root = Path(root)
    catalog_dir = root / "_index" / "interface-catalog"
    catalog_paths = sorted(
        p for p in catalog_dir.rglob("*.yaml")
        # Skip anything under a dot-directory (e.g. .claude/worktrees leftovers).
        if not any(seg.startswith(".") for seg in p.relative_to(catalog_dir).parts[:-1])
    )

    failures: list = []
    written = 0

    for cat_path in catalog_paths:
        # Derive domain path from catalog path (strip .yaml suffix)
        rel = cat_path.relative_to(catalog_dir)          # eu/schengen-90-180.yaml
        domain_id = str(rel.with_suffix(""))              # eu/schengen-90-180
        spec_path = root / domain_id / "INTERFACE-SPEC.md"

        catalog = yaml.safe_load(cat_path.read_text())
        content = render_spec(catalog)

        if check:
            if not spec_path.exists() or spec_path.read_text() != content:
                failures.append(str(spec_path))
        else:
            spec_path.parent.mkdir(parents=True, exist_ok=True)
            spec_path.write_text(content)
            written += 1

    if check:
        if failures:
            print(f"STALE: {len(failures)} INTERFACE-SPEC.md file(s) would change:")
            for p in failures:
                print(f"  {p}")
            return 1
        print(
            f"OK: {len(catalog_paths)} domains,"
            " all INTERFACE-SPEC.md files up to date."
        )
        return 0

    print(f"Wrote {written} INTERFACE-SPEC.md files.")
    return 0


# ---------------------------------------------------------------------------
# CLI
# ---------------------------------------------------------------------------

def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Generate per-domain INTERFACE-SPEC.md from the interface catalog."
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Exit non-zero if any INTERFACE-SPEC.md would change (CI guard).",
    )
    args = parser.parse_args(argv)
    root = Path(__file__).resolve().parent.parent  # clausify-domains root
    sys.exit(run(root, check=args.check))


if __name__ == "__main__":
    main()
