class TestParseImports:
    def test_import_from_single_line(self):
        m = imp()
        text = "-import_from(formalize_lib, [profile_get, profile_has, attribute])\n"
        imports = m.parse_imports(text)
        assert len(imports) == 1
        assert imports[0]['module'] == 'formalize_lib'
        assert 'profile_get' in imports[0]['names']

    def test_import_from_multiline(self):
        m = imp()
        text = textwrap.dedent("""\
            -import_from(formalize_lib, [profile_get, profile_has, attribute,
                                         item, unmet, unknown, labels,
                                         decide_labeled])
        """)
        imports = m.parse_imports(text)
        assert len(imports) == 1
        assert 'decide_labeled' in imports[0]['names']

    def test_import_module(self):
        m = imp()
        text = "-import_module(diversity_jurisdiction)\n"
        imports = m.parse_imports(text)
        assert len(imports) == 1
        assert imports[0]['module'] == 'diversity_jurisdiction'
        assert imports[0]['kind'] == 'import_module'

    def test_multiple_imports(self):
        m = imp()
        text = textwrap.dedent("""\
            -import_from(formalize_lib, [profile_get, profile_has])
            -import_from(date_time, [date, date_between])
        """)
        imports = m.parse_imports(text)
        assert len(imports) == 2
        modules = {i['module'] for i in imports}
        assert modules == {'formalize_lib', 'date_time'}

    def test_import_from_multiline_with_comment_block(self):
        """Comment lines inside a multi-line -import_from list must not pollute
        the names list (Bug 2 — comment text in import names)."""
        m = imp()
        text = textwrap.dedent("""\
            -import_from(special_category_inference, [
                art9_category, inferred_special_category,
                # Art 9(1) category VALUE atoms + the biometric-purpose value atom.
                # These are imported so the oracle/tests share ONE functor identity.
                racial_ethnic_origin, political_opinions,
                religious_philosophical_beliefs
            ])
        """)
        imports = m.parse_imports(text)
        assert len(imports) == 1
        names = imports[0]['names']
        assert 'racial_ethnic_origin' in names, \
            "racial_ethnic_origin must appear despite being on the line after comments"
        assert 'art9_category' in names
        assert 'religious_philosophical_beliefs' in names
        # No name should contain '#' or multi-word comment text
        assert not any('#' in n for n in names), \
            f"Comment text leaked into names: {[n for n in names if '#' in n]}"
        assert not any(len(n.split()) > 1 for n in names), \
            f"Multi-word comment text leaked into names: {[n for n in names if len(n.split()) > 1]}"


    def test_import_from_dotted_module(self):
        """Sibling re-export in a thin package init uses a dotted module name
        (us.snap.schema) — the \\w+ module regex must allow dots."""
        m = imp()
        text = "-import_from(us.snap.schema, [amount, eligible, met])\n"
        imports = m.parse_imports(text)
        assert len(imports) == 1
        assert imports[0]['module'] == 'us.snap.schema'
        assert imports[0]['names'] == ['amount', 'eligible', 'met']


