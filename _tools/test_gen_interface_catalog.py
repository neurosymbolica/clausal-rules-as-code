THIN_INIT_TEXT = textwrap.dedent("""\
    # us.snap/__init__.seam -- thin package init.
    -import_from(us.snap.schema, [amount, eligible, ineligible, met])
    -import_from(us.snap.computation, [snap_net_income, snap_gross_income])
    -import_from(formalize_lib, [assessment, item, unmet, unknown])
""")


class TestThinPackageInit:
    def test_detects_thin_init_with_package_path(self, tmp_path):
        m = imp()
        p = tmp_path / "__init__.seam"
        p.write_text(THIN_INIT_TEXT)
        assert m.is_thin_package_init(p, THIN_INIT_TEXT, "us.snap") is True

    def test_not_thin_init_when_module_directive_present(self, tmp_path):
        m = imp()
        text = "-module(snap, [amount(A,B,C,D)])\n" + THIN_INIT_TEXT
        p = tmp_path / "__init__.seam"
        p.write_text(text)
        # posted_workers still-monolith case: __init__.clausal WITH a -module
        assert m.is_thin_package_init(p, text, "us.snap") is False

    def test_not_thin_init_when_wrong_filename(self, tmp_path):
        m = imp()
        p = tmp_path / "schema.seam"
        p.write_text(THIN_INIT_TEXT)
        assert m.is_thin_package_init(p, THIN_INIT_TEXT, "us.snap") is False

    def test_process_rulebase_classifies_package_init(self, tmp_path):
        m = imp()
        p = tmp_path / "__init__.seam"
        p.write_text(THIN_INIT_TEXT)
        info = m.process_rulebase(p, tmp_path, set(), package_path="us.snap")
        assert info["role"] == "package_init"
        assert info["module"] is None
        # No spurious "No -module directive found" warning
        assert not info.get("warnings")
        # Re-export union is the package public surface
        exports = info["package_init_exports"]
        assert "amount" in exports
        assert "snap_net_income" in exports
        assert "assessment" in exports  # additive compat re-export from formalize_lib

    def test_drift_by_name_against_package_init(self, tmp_path):
        m = imp()
        manifest = tmp_path / "manifest.yaml"
        manifest.write_text(textwrap.dedent("""\
            shape_family: eligibility
            public_interface:
              - "amount/4"
              - "snap_net_income/2"
        """))
        # code surface (bare names) missing snap_gross_income -> in_code_not_manifest
        result = m.compare_manifest_drift_names(
            manifest, ["amount", "snap_net_income", "snap_gross_income"]
        )
        assert result["in_code_not_manifest"] == ["snap_gross_income"]
        assert result["in_manifest_not_code"] == []
        assert result["drift"] is True

    def test_drift_false_when_names_match(self, tmp_path):
        m = imp()
        manifest = tmp_path / "manifest.yaml"
        manifest.write_text(textwrap.dedent("""\
            shape_family: eligibility
            public_interface:
              - "amount/4"
              - "met/0"
        """))
        result = m.compare_manifest_drift_names(manifest, ["amount", "met"])
        assert result["drift"] is False

    def test_process_domain_uses_package_init_surface(self, tmp_path):
        """Internal sibling plumbing forced onto a sibling's -module export must
        NOT count as public; only the thin init's re-export union does."""
        m = imp()
        dom = tmp_path / "us" / "snap"
        dom.mkdir(parents=True)
        # The thin init re-exports the PUBLIC surface only: a predicate (amount)
        # and a bare enum atom (eligible).  It does NOT re-export max0 — that
        # helper is only forced onto the computation sibling's -module export so
        # a cross-sibling importer can name it; it is internal plumbing.
        (dom / "__init__.seam").write_text(
            "-import_from(us.snap.computation, [amount])\n"
            "-import_from(us.snap.schema, [eligible])\n"
        )
        # computation exports amount (public pred, on the facade) AND max0
        # (internal helper, forced onto the sibling export but NOT re-exported
        # by the thin init).
        (dom / "computation.seam").write_text(textwrap.dedent("""\
            -module(computation, [amount(A,B,C,D), max0(X,Y)])
            amount(A,B,C,D) <- (true)
            max0(X,Y) <- (true)
        """))
        # schema exports the bare enum atom eligible (no clause head)
        (dom / "schema.seam").write_text(
            "-module(schema, [eligible])\n"
        )
        # manifest lists PREDICATES/CONSTRUCTORS only (its convention): amount.
        # The atom eligible and the internal helper max0 are NOT listed.
        (dom / "manifest.yaml").write_text(textwrap.dedent("""\
            shape_family: eligibility
            public_interface:
              - "amount/4"
        """))
        catalog = m.process_domain(dom, tmp_path, set())
        # max0 (not re-exported by the thin init) and eligible (atom) are both
        # excluded from the drift comparison -> no drift.  The OLD union-of-all-
        # siblings deriver would have flagged max0 as in_code_not_manifest.
        assert catalog["manifest"]["drift"] is False, catalog["manifest"]
        # multi_rulebase excludes the thin init from the logic-file count
        assert catalog["multi_rulebase"] is True

    def test_process_domain_falls_back_without_init(self, tmp_path):
        """A domain with a -module __init__ (still-monolith) uses legacy
        union-of-sibling-exports drift, not the package_init path."""
        m = imp()
        dom = tmp_path / "eu" / "labour" / "pw"
        dom.mkdir(parents=True)
        (dom / "__init__.seam").write_text(textwrap.dedent("""\
            -module(pw, [trigger(A,B)])
            trigger(A,B) <- (true)
        """))
        (dom / "manifest.yaml").write_text(textwrap.dedent("""\
            shape_family: temporal
            public_interface:
              - "trigger/2"
        """))
        catalog = m.process_domain(dom, tmp_path, set())
        assert catalog["manifest"]["drift"] is False


