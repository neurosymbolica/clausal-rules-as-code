class TestDeterminism:
    def test_run_twice_byte_identical(self, tmp_path):
        """Running gen_interface_catalog.py twice produces identical output."""
        import subprocess
        root = Path(__file__).resolve().parent.parent
        out_dir = tmp_path / "out1"
        out_dir.mkdir()

        script = root / "_tools/gen_interface_catalog.py"
        if not script.exists():
            pytest.skip("gen_interface_catalog.py not yet implemented")

        import subprocess
        # Run once into out1, once into out2, compare
        env_args = ["python3", str(script), "--output-dir", str(tmp_path / "out1")]
        result1 = subprocess.run(env_args, capture_output=True, cwd=str(root))
        result2 = subprocess.run(env_args, capture_output=True, cwd=str(root))
