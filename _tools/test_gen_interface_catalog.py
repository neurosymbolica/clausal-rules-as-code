class TestFindClauseHeads:
    def test_simple_rule_head(self):
        m = imp()
        body = "days_used(SCENARIO, DAYS) <- (foo, bar)\n"
        heads = m.find_clause_heads(body)
        assert ('days_used', 2) in heads

    def test_fact_head(self):
        m = imp()
        body = "short_stay_limit_days(90),\n"
        heads = m.find_clause_heads(body)
        assert ('short_stay_limit_days', 1) in heads

    def test_bare_atom_fact(self):
        m = imp()
        body = "compliant,\n"
        heads = m.find_clause_heads(body)
        assert ('compliant', 0) in heads

    def test_indented_body_not_a_head(self):
        m = imp()
        body = "foo(X) <- (\n    bar(X),\n    baz(X)\n)\n"
        heads = m.find_clause_heads(body)
        assert ('bar', 1) not in heads
        assert ('foo', 1) in heads

    def test_comment_line_ignored(self):
        m = imp()
        body = "# foo(X),\nreal_head(Y),\n"
        heads = m.find_clause_heads(body)
        assert ('foo', 1) not in heads
        assert ('real_head', 1) in heads

    def test_multiline_fact_head_arity(self):
        """Fact whose second arg is a list literal continuing on the next line:
        arity must be 2, not 1 (Bug 1 — multi-line clause-head arity)."""
        m = imp()
        body = textwrap.dedent("""\
            snap_profile_for("subject_eligible",
                [attribute("earned_income_usd", 1000), attribute("household_size", 1)]),
        """)
        heads = m.find_clause_heads(body)
        assert ('snap_profile_for', 2) in heads, \
            "snap_profile_for/2 must be recognised as a clause head even when args span lines"
        assert ('snap_profile_for', 1) not in heads, \
            "wrong arity 1 must NOT appear for a 2-arg head"

    def test_multiline_fact_three_args_spanning_lines(self):
        """Profile-for fact with a three-element signature spread across two lines."""
        m = imp()
        body = textwrap.dedent("""\
            visa_requirement_ids("visa_exempt_60",
                ["req_nationality_p60", "req_passport_valid_6mo",
                 "req_funds_exempt", "req_onward_ticket"]),
        """)
        heads = m.find_clause_heads(body)
        assert ('visa_requirement_ids', 2) in heads
        assert ('visa_requirement_ids', 1) not in heads


