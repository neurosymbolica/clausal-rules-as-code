class TestExtractModuleDirective:
    def test_simple_one_liner(self):
        m = imp()
        text = "-module(mymod, [foo(X), bar])\n"
        name, exports = m.extract_module_directive(text)
        assert name == "mymod"
        assert "foo(X)" in exports
        assert "bar" in exports

    def test_multiline(self):
        m = imp()
        text = textwrap.dedent("""\
            -module(schengen, [
                days_used(SCENARIO, DAYS),
                compliance(SCENARIO, STATUS),
                compliant, non_compliant,
            ])
        """)
        name, exports = m.extract_module_directive(text)
        assert name == "schengen"
        assert "days_used(SCENARIO, DAYS)" in exports
        assert "compliant" in exports

    def test_no_module_raises(self):
        m = imp()
        with pytest.raises(ValueError, match="No -module"):
            m.extract_module_directive("# just a comment\nfoo(X),\n")

    def test_deeply_nested_args(self):
        """Functor with list arg containing brackets: stay([Y,M,D],[Y,M,D])"""
        m = imp()
        text = "-module(x, [stay([Y,M,D],[Y2,M2,D2]), done])\n"
        name, exports = m.extract_module_directive(text)
        assert name == "x"
        assert "stay([Y,M,D],[Y2,M2,D2])" in exports


class TestParseExportsText:
    def test_predicate_and_bare_atoms(self):
        m = imp()
        text = textwrap.dedent("""\
            days_used(SCENARIO, DAYS),
            compliant, non_compliant,
        """)
        items, gen_keys = m.parse_exports_text(text)
        names = {i['name'] for i in items}
        assert 'days_used' in names
        assert 'compliant' in names
        assert 'non_compliant' in names
