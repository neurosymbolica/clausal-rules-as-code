#!/usr/bin/env python3
"""scaffold_translation.py -- scaffold a domain's per-language translation
submodule (Part C; docs/superpowers/specs/2026-07-18-translation-population-design.md).

Writes one translation(<atom>, {ref, verbatim}) record per citation atom (read
from the domain's citations.clausal) into translation/<lang>.clausal. The bare
atoms are declared via -import_from(<pkg>.citations, [...]) so they share identity
with the citation atoms (the join key). Purely additive: never touches
citations.clausal or any logic file. Idempotent: populated records survive.
"""
from _tools.source_files import resolve_source, write_target
import argparse, os, re, subprocess, sys

#: The repository root (this file is _tools/scaffold_translation.py), wherever the repository is checked out.
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

_NAME = r"[a-z][a-z0-9_]*"
# a citation record's bare-atom key in citations.clausal: citation(<atom>, { ... })
_CIT_REC_RE = re.compile(r"citation\(\s*(" + _NAME + r")\s*,\s*\{")

def citation_atoms(citations_source):
    """The citation atoms owning a citation/2 record in a domain's
    citations.clausal -- the translatable key set. Sorted, deduped."""
    seen = []
    for m in _CIT_REC_RE.finditer(citations_source):
        a = m.group(1)
        if a not in seen:
            seen.append(a)
    return sorted(seen)

_HEADER = """\
# translation/<lang>.clausal -- official-language rendition of this domain's
# citation verbatim text (Part C; docs/superpowers/specs/
# 2026-07-18-translation-population-design.md). One translation(<atom>, {ref,
# verbatim}) per citation atom; the atom is the SAME key citations.clausal uses
# (imported below for shared identity). English is the default, carried by
# citation/2 -- NOT duplicated here.
#
# Purely additive & load-on-demand: this file is NEVER imported by __init__; a
# consumer loads <pkg>.translation.<lang> explicitly. verbatim is an exact
# substring of the fetched target-language EUR-Lex CELEX source (see the
# <lang>-sources.yaml audit manifest). Generated by _tools/scaffold_translation.py;
# hand-edit only ref/verbatim.
"""

def _render_empty_record(atom):
    return (
        f"translation({atom}, {{\n"
        f'  "ref":      "",\n'
        f'  "verbatim": ""\n'
        "}),"
    )

_RECORD_BLOCK_RE = re.compile(
    r"translation\(\s*(?P<atom>" + _NAME + r")\s*,\s*\{.*?\}\)\s*,", re.DOTALL)

def parse_existing_records(translation_source):
    blocks = {}
    for m in _RECORD_BLOCK_RE.finditer(translation_source):
        blocks[m.group("atom")] = m.group(0)
    return blocks

def render_translation_module(atoms, pkg, lang, existing_blocks=None):
    """Render translation/<lang>.clausal. Atoms with an existing populated block
    keep it byte-for-byte (idempotent re-runs); others get a fresh empty record."""
    existing_blocks = existing_blocks or {}
    imp = f"-import_from({pkg}.citations, [{', '.join(atoms)}])"
    lines = [_HEADER, "", f"-module({lang}, [translation(ATOM, META)])", "",
             imp, "", "-strict_atoms", ""]
    for a in atoms:
        lines.append(existing_blocks.get(a) or _render_empty_record(a))
        lines.append("")
    return "\n".join(lines) + "\n"

def _pkg_from_dir(domain_dir, repo_root=REPO_ROOT):
    rel = os.path.relpath(os.path.abspath(domain_dir), repo_root)
    return rel.replace(os.sep, ".")

class Changeset:
    def __init__(self):
        self.writes = {}   # path -> content

def build_changeset(domain_dir, lang):
    """Render translation/<lang>.clausal from the domain's citation atoms.
    Preserves populated records (idempotent). NEVER writes citations.clausal or
    any logic file."""
    pkg = _pkg_from_dir(domain_dir)
    atoms = citation_atoms(
        open(resolve_source(os.path.join(domain_dir, "citations.clausal")),
             encoding="utf-8").read())
    tpath = str(write_target(os.path.join(domain_dir, "translation", lang + ".clausal")))
    existing = {}
    if os.path.exists(tpath):
        existing = parse_existing_records(open(tpath, encoding="utf-8").read())
    cs = Changeset()
    cs.writes[tpath] = render_translation_module(atoms, pkg, lang, existing)
    return cs

def apply(domain_dir, lang, stage=True):
    cs = build_changeset(domain_dir, lang)
    for path, content in cs.writes.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
        if stage:
            subprocess.run(["git", "add", path],
                           cwd=REPO_ROOT, check=True)

def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("domain_dir")
    ap.add_argument("--lang", required=True, help="target language code, e.g. fr")
    ap.add_argument("--apply", action="store_true")
    ap.add_argument("--no-stage", action="store_true")
    a = ap.parse_args(argv)
    if a.apply:
        apply(a.domain_dir, a.lang, stage=not a.no_stage)
        print("applied:", a.domain_dir, a.lang)
        return 0
    cs = build_changeset(a.domain_dir, a.lang)
    for path, content in cs.writes.items():
        print("=== " + path + " ===")
        print(content)
    return 0

if __name__ == "__main__":
    sys.exit(main())
