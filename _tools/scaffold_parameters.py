#!/usr/bin/env python3
"""scaffold_parameters.py -- decision-preserving scaffold of a domain's
parameters.clausal submodule (Part B; docs/superpowers/specs/
2026-07-17-citation-partB-parameter-provenance-design.md).

Writes one parameter_source("<functor>", {label, ref, verbatim}) record per
curated functor (the top-level keys of parameters-sources.yaml). Purely
additive: the value facts stay in the logic module; this scaffold NEVER edits
it. Idempotent: populated records survive a re-run byte-for-byte.
"""
from _tools.source_files import is_source, source_stem, resolve_source
import argparse, os, re, subprocess, sys

#: The repository root (this file is _tools/scaffold_parameters.py), wherever the repository is checked out.
REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
try:
    import yaml
except ImportError:
    yaml = None

_NAME = r"[a-z][a-z0-9_]*"
# a ground-fact line: functor(args), optionally + trailing comment, whole line.
# Requiring the line to END at '),' (before any comment) excludes rule clauses
# (which contain '<-' and end at ') <- (body)') and nested-paren terms.
_FACT_RE = re.compile(
    r"^(?P<fn>" + _NAME + r")\((?P<args>[^)]*)\)\s*,(?:[ \t]*#(?P<cmt>.*))?$",
    re.MULTILINE,
)

def candidate_facts(logic_source):
    """Ground facts functor(args) carrying >=1 integer arg, one per DISTINCT
    functor (first occurrence). A SEED aid for curation — over-matching is fine;
    the human prunes. Rule clauses never match (they contain '<-')."""
    out, seen = [], set()
    for m in _FACT_RE.finditer(logic_source):
        args = m.group("args")
        if not re.search(r"\d", args):
            continue
        fn = m.group("fn")
        if fn in seen:
            continue
        seen.add(fn)
        arity = len([a for a in args.split(",") if a.strip()])
        out.append({
            "functor": fn,
            "arity": arity,
            "sample": (m.group("fn") + "(" + args + ")"),
            "comment": (m.group("cmt") or "").strip(),
        })
    return out

_HEADER = """\
# parameters.clausal -- machine-readable provenance for this domain's
# legally-sourced parameter VALUES (Part B; docs/superpowers/specs/
# 2026-07-17-citation-partB-parameter-provenance-design.md). Purely additive:
# the value facts stay in the logic module; these rows only REFERENCE them by
# functor name. Load-on-demand -- NOT imported by the logic module.
#
# Owns parameter_source/2: parameter_source("<functor>", {label, ref, verbatim}).
# The verbatim MUST state the value in the source's own units; the functor's
# unit suffix (_cents/_bps/_percent/_days) bridges to the machine value.
# Generated by _tools/scaffold_parameters.py from parameters-sources.yaml keys;
# hand-edit only label/ref/verbatim. Regenerate structure; never hand-add keys.
"""

def _render_empty_record(functor):
    return (
        f'parameter_source("{functor}", {{\n'
        f'  label:    "",\n'
        f'  ref:      "",\n'
        f'  verbatim: ""\n'
        "}),"
    )

def render_parameters_module(functors, existing_blocks=None):
    """Render parameters.clausal. Functors with an entry in existing_blocks keep
    their raw on-disk record byte-for-byte (idempotent re-runs never touch
    populated label/ref/verbatim); others get a fresh empty record."""
    existing_blocks = existing_blocks or {}
    lines = [_HEADER, "", "-module(parameters, [parameter_source(KEY, META)])",
             # `-double_quotes(chars)` is EMITTED, not assumed. The scaffold never wrote it,
             # so re-rendering a domain DELETED the directive from a file that had it --
             # measured on eu/procurement/life_cycle_costing, whose only diff after a
             # re-render was the directive going missing. It decides how every label /
             # ref / verbatim literal in the file is read, so losing it silently changes
             # what the records MEAN, and the file still loads.
             "-double_quotes(chars)",
             "-private([label, ref, units, verbatim])", "", "-strict_atoms", ""]
    for fn in functors:
        lines.append(existing_blocks.get(fn) or _render_empty_record(fn))
        lines.append("")
    return "\n".join(lines) + "\n"

_RECORD_BLOCK_RE = re.compile(
    r'parameter_source\(\s*"(?P<key>' + _NAME + r')"\s*,\s*\{.*?\}\)\s*,',
    re.DOTALL,
)

def parse_existing_records(parameters_source):
    blocks = {}
    for m in _RECORD_BLOCK_RE.finditer(parameters_source):
        blocks[m.group("key")] = m.group(0)
    return blocks

def curated_functors(sources_yaml_text):
    """The curated parameter-functor set = the top-level keys of
    parameters-sources.yaml (the sourcing agent's recorded curation decision).
    Sorted for deterministic output."""
    data = yaml.safe_load(sources_yaml_text) or {}
    return sorted(data)

class Changeset:
    def __init__(self):
        self.writes = {}   # path -> content

def build_changeset(domain_dir):
    """Render parameters.clausal from the curated functor list. Preserves any
    populated record for a still-listed functor (idempotent). NEVER writes the
    logic module — Part B is purely additive."""
    spath = os.path.join(domain_dir, "parameters-sources.yaml")
    functors = curated_functors(open(spath, encoding="utf-8").read())
    ppath = str(resolve_source(os.path.join(domain_dir, "parameters.clausal")))
    existing = {}
    if os.path.exists(ppath):
        existing = parse_existing_records(open(ppath, encoding="utf-8").read())
    cs = Changeset()
    cs.writes[ppath] = render_parameters_module(functors, existing)
    return cs

def apply(domain_dir, stage=True):
    cs = build_changeset(domain_dir)
    for path, content in cs.writes.items():
        with open(path, "w", encoding="utf-8") as fh:
            fh.write(content)
        if stage:
            subprocess.run(["git", "add", path],
                           cwd=REPO_ROOT, check=True)

def _logic_files(domain_dir):
    return [f for f in sorted(os.listdir(domain_dir))
            if is_source(f) and source_stem(f) not in
            ("parameters", "citations")]

def main(argv=None):
    ap = argparse.ArgumentParser()
    ap.add_argument("domain_dir")
    ap.add_argument("--seed", action="store_true",
                    help="print candidate numeric ground-fact functors for curation")
    ap.add_argument("--apply", action="store_true",
                    help="write parameters.clausal from parameters-sources.yaml keys")
    ap.add_argument("--no-stage", action="store_true",
                    help="write but do not git-add (safe for parallel callers)")
    a = ap.parse_args(argv)
    if a.seed:
        for f in _logic_files(a.domain_dir):
            src = open(os.path.join(a.domain_dir, f), encoding="utf-8").read()
            for c in candidate_facts(src):
                print(f'{c["functor"]}/{c["arity"]}\t# {c["comment"]}')
        return 0
    if a.apply:
        apply(a.domain_dir, stage=not a.no_stage)
        print("applied:", a.domain_dir)
        return 0
    cs = build_changeset(a.domain_dir)
    for path, content in cs.writes.items():
        print("=== " + path + " ===")
        print(content)
    return 0

if __name__ == "__main__":
    sys.exit(main())
